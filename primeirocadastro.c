//Vamos criar um pequeno cadastro.
#include <stdio.h>

int main()
{
  int idade = 20;
  float nota = 8.5;
  char turma = 'A';
  printf("Idade: %d\n" ,idade);
  printf("Nota: %.1f\n" ,nota);
  printf("Turma: %c" ,turma);

  return 0;
}

/*Resultado:
Idade:20
Nota :8.5
Turma: A
Perceba que o programa já está armazenando informações.*/